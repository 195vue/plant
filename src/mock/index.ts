const RETENTIONS: DocumentItem["retention"][] = ["permanent", "long", "short30", "short10", "short5"];
const CARRIERS: DocumentItem["carrier"][] = ["electronic", "paper", "both"];
const FILING_UNITS = ["机电检修部", "水工运维部", "设备管理部", "安全质量部", "工程技术部", "档案室"];

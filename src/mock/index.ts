// 为设备实例按其类型模板生成属性列表
function buildEquipmentAttributes(eq: Equipment): EquipmentAttribute[] {
  const templateKey = attrTypeMap[eq.type] || eq.type;
  const group = equipmentAttrTemplates[templateKey];
  if (!group) return [];
  const attrs: EquipmentAttribute[] = [];
  let attrId = 1;
  group.categories.forEach((cat) => {
    cat.attrs.forEach((attr) => {
      let value = "";
      // 动态填充已知字段
      if (attr.name === "设备名称") value = eq.name;
      else if (attr.name === "KKS编码") value = eq.code;
      else if (attr.name === "唯一编码") value = eq.code;
      else if (attr.name === "编码") value = group.className;
      else if (attr.name === "型号") value = eq.model || attr.defaultValue || "";
      else value = attrSampleValues[attr.name] || attr.defaultValue || "";
      attrs.push({
        id: attrId++,
        equipmentId: eq.id,
        name: attr.name,
        value,
        type: "text" as const,
        unit: attr.unit || "",
        category: cat.name,
      });
    });
  });
  return attrs;
}

// 给每台设备自动生成属性

const pad = (n: number) => String(n).padStart(2, "0");
function addFields(raw: Omit<DocumentItem, "archiveNo"|"secretLevel"|"retention"|"carrier"|"archiveDate"|"archivist"|"filingUnit"|"filingUser"|"filingDate"|"viewCount"|"downloadCount"|"borrowCount">, idx: number): DocumentItem {
  const y = String(raw.uploadTime).slice(0, 4);
  const mm = String(raw.uploadTime).slice(5, 7);
  const seq = pad(idx);
  const catShort =
    raw.category === "设备说明书" ? "SB" :
    raw.category === "检修记录" ? "JX" :
    raw.category === "验收报告" ? "YS" :
    raw.category === "检测报告" ? "JC" :
    raw.category === "设计图纸" ? "SJ" :
    raw.category === "竣工图纸" ? "JG" :
    raw.category === "照片影像" ? "ZP" :
    raw.category === "操作规程" ? "GC" : "QT";
  const archiveNo = `ZLDP-${catShort}-${y}-${mm}-${seq}`;
  const isApproved = raw.approvalStatus === "approved";
  const isArchived = isApproved && (idx % 4 === 0);
  const approvalStatus: DocumentItem["approvalStatus"] = isArchived ? "archived" : raw.approvalStatus || "pending";
  const date = new Date(String(raw.uploadTime).replace(" ", "T"));
  const filingDate = `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())} ${pad(date.getHours())}:${pad(date.getMinutes())}:${pad(date.getSeconds())}`;
  const archiveDate = (() => {
    if (!isArchived) return undefined;
    const d = new Date(date);
    d.setDate(d.getDate() + 7);
    return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())} ${pad(d.getHours())}:${pad(d.getMinutes())}:${pad(d.getSeconds())}`;
  })();
  return {
    ...raw,
    archiveNo,
    secretLevel: SECRET_LEVELS[idx % SECRET_LEVELS.length],
    retention: RETENTIONS[idx % RETENTIONS.length],
    carrier: CARRIERS[idx % CARRIERS.length],
    filingUnit: FILING_UNITS[idx % FILING_UNITS.length],
    filingUser: USERS[(idx + 1) % USERS.length],
    filingDate,
    archivist: isArchived ? "王档案" : undefined,
    archiveDate,
    approvalStatus,
    viewCount: 5 + ((idx * 7) % 80),
    downloadCount: 1 + ((idx * 3) % 30),
    borrowCount: (idx % 3 === 0) ? (1 + (idx % 5)) : 0,
  };
}
